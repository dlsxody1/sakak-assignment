/**
 * 실패 원인 → 사용자에게 보여줄 문장.
 *
 * API 원문 메시지를 그대로 노출하지 않는다(카피 규칙). 대신 **사용자가 다음에
 * 뭘 할지**를 상태코드별로 말한다 — "실패했습니다" 하나로 뭉치면 재시도하면
 * 될 일(502)과 입력을 고쳐야 할 일(400)이 구분되지 않는다.
 *
 * 순수 함수라 `lib/`에 있다. 렌더링 없이 상태코드만으로 검증된다.
 */

/** `fetch` 자체가 실패한 경우. 네트워크가 끊겼거나 서버에 닿지 못했다. */
export const NETWORK_MESSAGE =
  '네트워크에 연결하지 못했습니다. 연결을 확인하고 다시 시도해 주세요.'

/**
 * 프록시(`api/checkup.ts`)와 CANDiY가 함께 쓰는 상태코드다.
 * 프록시는 상위 상태를 그대로 넘기므로 두 출처가 같은 표에 걸린다.
 */
export function messageForStatus(status: number): string {
  // 400·422 — 프록시의 필수 필드 검사나 CANDiY의 입력 거절.
  if (status === 400 || status === 422) {
    return '입력한 정보를 다시 확인해 주세요. 이름·생년월일·휴대폰 번호가 실제 가입 정보와 같아야 합니다.'
  }

  // 401·403 — 키가 거절됐다. 사용자가 고칠 수 있는 게 없다.
  if (status === 401 || status === 403) {
    return '검진 조회 권한이 확인되지 않았습니다. 잠시 후 다시 시도해 주세요.'
  }

  if (status === 404) {
    return '조회한 검진 정보를 찾지 못했습니다.'
  }

  // 408·504 — 상위가 제때 답하지 않았다. 인증 제한 시간과 겹칠 수 있어 따로 말한다.
  if (status === 408 || status === 504) {
    return '응답이 지연되어 조회를 마치지 못했습니다. 처음부터 다시 시도해 주세요.'
  }

  if (status === 429) {
    return '요청이 많아 잠시 제한되었습니다. 1분 뒤에 다시 시도해 주세요.'
  }

  // 5xx — 우리 쪽 문제다. 사용자가 입력을 고쳐도 달라지지 않으니 그렇게 말하지 않는다.
  if (status >= 500) {
    return '검진 조회 서버에 문제가 있습니다. 잠시 후 다시 시도해 주세요.'
  }

  return '검진 결과를 불러오지 못했습니다. 잠시 후 다시 시도해 주세요.'
}
